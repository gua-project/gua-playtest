    public static IEnumerable<object[]> OperatorTypeMatrix()
    {
        // Independent normative allow table, including every scalar and every collection element type.
        string[] universal = ["equals", "notEquals"];
        string[] numeric = ["greaterThan", "greaterThanOrEqual", "lessThan", "lessThanOrEqual"];
        string[] strings = ["contains", "startsWith", "endsWith", "matches"];
        string[] collections = ["contains", "notContains", "containsAll", "containsAny", "isEmpty", "isNotEmpty", "countEquals", "countNotEquals", "countGreaterThan", "countGreaterThanOrEqual", "countLessThan", "countLessThanOrEqual"];
        string[] sequences = ["sequenceEquals", "startsWithSequence", "endsWithSequence", "containsSequence"];
        var ops = universal.Concat(numeric).Concat(strings).Concat(collections).Concat(sequences).Append("approximatelyEquals").Distinct().ToArray();
        foreach (var kind in new[] { "bool", "integer", "number", "string", "enum", "list", "set" })
        foreach (var element in kind is "list" or "set" ? new[] { "bool", "integer", "number", "string", "enum" } : new string?[] { null })
        foreach (var op in ops)
        {
            var allowed = universal.Contains(op) || (kind is "integer" or "number" && numeric.Contains(op))
                || (kind == "number" && op == "approximatelyEquals") || (kind == "string" && strings.Contains(op))
                || (kind is "list" or "set" && collections.Contains(op)) || (kind == "list" && sequences.Contains(op));
            yield return [kind, element!, op, allowed];
        }
    }

    [Theory]
    [MemberData(nameof(OperatorTypeMatrix))]
    public void EveryOperatorTypeCombinationIsAcceptedOrRejected(string kind, string? element, string op, bool allowed)
    {
        static string Token(string kind) => kind switch { "bool" => "true", "integer" or "number" => "1", "enum" => "\"First\"", _ => "\"x\"" };
        var sample = Value(kind, element is null ? Token(kind) : "[" + Token(element) + "]", element);
        JsonObject? expected = op is "isEmpty" or "isNotEmpty" ? null : op.StartsWith("count", StringComparison.Ordinal) ? Value("integer", "1")
            : op is "contains" or "notContains" && element is not null ? Value(element, Token(element)) : sample;
        var config = Assertion(TypeOf(sample), op, expected, op == "approximatelyEquals" ? 0 : null);
        if (allowed)
        {
            var prepared = PreparedAssertion.Create(config, Limits, Catalog());
            Assert.Equal(EvaluationError.None, prepared.Evaluate(sample, Catalog()).Error);
        }
        else Assert.Throws<AssertionConfigurationException>(() => PreparedAssertion.Create(config, Limits, Catalog()));
    }

    [Theory]
    [InlineData("9007199254740992")]
    [InlineData("-9007199254740992")]
    [InlineData("1.00000000000000001")]
    [InlineData("0.999999999999999999999999999999999")]
    [InlineData("1e-400")]
    public void IntegerIsValidatedBeforeRounding(string token)
    {
        var expected = Value("integer", token);
        Assert.Throws<AssertionConfigurationException>(() => PreparedAssertion.Create(Assertion("{\"type\":\"integer\"}", "equals", expected), Limits));
        var prepared = PreparedAssertion.Create(Assertion("{\"type\":\"integer\"}", "notEquals", Value("integer", "1")), Limits);
        Assert.Equal(EvaluationError.ObservationContractViolation, prepared.Evaluate(expected).Error);
    }

    [Fact]
    public void MismatchedTypesAreConfigurationErrorsOrObservationViolations()
    {
        var list = Value("list", "[\"x\"]", "string");
        Assert.Throws<AssertionConfigurationException>(() => PreparedAssertion.Create(Assertion(TypeOf(list), "equals", Value("set", "[\"x\"]", "string")), Limits));
        Assert.Throws<AssertionConfigurationException>(() => PreparedAssertion.Create(Assertion("{\"type\":\"integer\"}", "equals", Value("number", "1")), Limits));
        var prepared = PreparedAssertion.Create(Assertion("{\"type\":\"integer\"}", "notEquals", Value("integer", "1")), Limits);
        Assert.Equal(EvaluationCode.TypeMismatch, prepared.Evaluate(Value("number", "2")).Code);
        Assert.Equal(EvaluationResult.Unknown(EvaluationCode.Missing), prepared.EvaluateUnavailable(EvaluationCode.Missing));
    }

    [Fact]
    public void EnumCollectionsPreserveTypeAndRequireApprovedConsistentCatalogs()
    {
        var list = Value("list", "[]", "enum");
        Assert.Throws<AssertionConfigurationException>(() => PreparedAssertion.Create(Assertion(TypeOf(list), "isEmpty"), Limits));
        var prepared = PreparedAssertion.Create(Assertion(TypeOf(list), "isEmpty"), Limits, Catalog());
        Assert.Equal(EvaluationResult.Known(true), prepared.Evaluate(list, Catalog()));
        Assert.Equal(EvaluationError.ObservationContractViolation, prepared.Evaluate(list).Error);
        Assert.Equal(EvaluationCode.EnumCatalogChanged, prepared.Evaluate(list, Catalog("\"First\",\"Second\"" )).Code);
        var changedType = Value("list", "[]", "enum"); changedType["enumType"] = "other.Phase";
        Assert.Throws<AssertionConfigurationException>(() => PreparedAssertion.Create(Assertion(TypeOf(list), "equals", changedType), Limits, Catalog()));
        foreach (var name in new[] { "Unknown", "1", "First|Second" })
            Assert.Throws<AssertionConfigurationException>(() => PreparedAssertion.Create(Assertion("{\"type\":\"enum\",\"enumType\":\"game.Phase\"}", "equals", Value("enum", "\"" + name + "\"")), Limits, Catalog()));
        var enumList = Value("list", "[\"First\",\"Second\"]", "enum");
        var contains = PreparedAssertion.Create(Assertion(TypeOf(enumList), "contains", Value("enum", "\"Second\"")), Limits, Catalog());
        Assert.Equal(EvaluationResult.Known(true), contains.Evaluate(enumList, Catalog()));
    }

