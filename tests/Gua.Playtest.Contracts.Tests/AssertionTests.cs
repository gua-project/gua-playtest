    private static readonly AssertionOptions Limits = new(10, 1000);
    private static JsonObject Json(string text) => JsonNode.Parse(text)!.AsObject();
    private static EnumCatalogSnapshot Catalog(string members = "\"First\",\"Second\",\"AliasSecond\"")
        => EnumCatalogSnapshot.Create(Json("{\"schemaVersion\":1,\"enums\":[{\"enumType\":\"game.Phase\",\"members\":[" + members + "]}]}"));

    private static JsonObject Assertion(string type, string op, JsonObject? expected = null, double? tolerance = null)
    {
        var result = Json("{\"kind\":\"assertion\",\"quantifier\":\"one\",\"read\":{\"target\":{\"source\":\"world\"},\"region\":\"property\",\"name\":\"value\",\"valueType\":" + type + "},\"operator\":\"" + op + "\"}");
        if (expected is not null) result["expected"] = expected.DeepClone();
        if (tolerance is not null) result["tolerance"] = tolerance;
        return result;
    }
    private static JsonObject Value(string kind, string token, string? element = null)
    {
        var value = Json("{\"type\":\"" + kind + "\",\"value\":" + token + "}");
        if (element is not null) value["elementType"] = element;
        if (kind == "enum" || element == "enum") value["enumType"] = "game.Phase";
        return value;
    }
    private static string TypeOf(JsonObject value)
    {
        var type = value.DeepClone().AsObject(); type.Remove("value"); return type.ToJsonString();
    }

