    [Fact]
    public void InvalidRegexAndLimitsFailEagerlyAndTimeoutRemainsUnknown()
    {
        var config = Assertion("{\"type\":\"string\"}", "matches", Value("string", "\"[\""));
        Assert.Equal("RegexInvalid", Assert.Throws<AssertionConfigurationException>(() => PreparedAssertion.Create(config, Limits)).Code);
        config["expected"] = Value("string", "\"abcd\"");
        Assert.Equal("RegexPatternTooLong", Assert.Throws<AssertionConfigurationException>(() => PreparedAssertion.Create(config, new(10, 3))).Code);
        foreach (var limits in new[] { new AssertionOptions(0, 10), new(-1, 10), new(10, 0), new(int.MaxValue, 10) })
            Assert.Throws<AssertionConfigurationException>(() => PreparedAssertion.Create(config, limits));
        config["expected"] = Value("string", "\"^(a+)+$\"");
        var regex = PreparedAssertion.Create(config, new(1, 100));
        var actual = new JsonObject { ["type"] = "string", ["value"] = new string('a', 20000) + "!" };
        Assert.Equal(EvaluationResult.Unknown(EvaluationCode.RegexTimeout), regex.Evaluate(actual)); // real catastrophic-backtracking fault
    }

    [Fact]
    public void PreparedExpectedAndCatalogAreSnapshots()
    {
        var config = Assertion("{\"type\":\"integer\"}", "equals", Value("integer", "1"));
        var prepared = PreparedAssertion.Create(config, Limits);
        config["expected"]!["value"] = 2;
        Assert.Equal(EvaluationResult.Known(true), prepared.Evaluate(Value("integer", "1")));
        var wire = Json("{\"schemaVersion\":1,\"enums\":[{\"enumType\":\"game.Phase\",\"members\":[\"First\"]},{\"enumType\":\"game.Phase\",\"members\":[\"First\"]}]}");
        var snapshot = EnumCatalogSnapshot.Create(wire);
        wire["enums"]![0]!["members"]![0] = "Second";
        var enumPrepared = PreparedAssertion.Create(Assertion("{\"type\":\"enum\",\"enumType\":\"game.Phase\"}", "equals", Value("enum", "\"First\"")), Limits, snapshot);
        Assert.Equal(EvaluationResult.Known(true), enumPrepared.Evaluate(Value("enum", "\"First\""), Catalog("\"First\"")));
        Assert.Equal("EnumConflict", Assert.Throws<AssertionConfigurationException>(() => EnumCatalogSnapshot.Create(wire)).Code);
    }

    [Fact]
    public void MalformedValueAndUnicodeAreNotOrdinaryFalse()
    {
        var prepared = PreparedAssertion.Create(Assertion("{\"type\":\"string\"}", "equals", Value("string", "\"x\"")), Limits);
        foreach (var bad in new[] { Json("{\"type\":\"string\",\"value\":null}"), Json("{\"type\":\"string\",\"value\":\"x\",\"secret\":\"do-not-print\"}"), new JsonObject { ["type"] = "string", ["value"] = "\ud800" } })
            Assert.Equal(EvaluationError.ObservationContractViolation, prepared.Evaluate(bad).Error);
        Assert.Throws<AssertionConfigurationException>(() => PreparedAssertion.Create(Assertion("{\"type\":\"string\"}", "equals", new JsonObject { ["type"] = "string", ["value"] = "\ud800" }), Limits));
    }

    [Fact]
    public async Task StaticLoadingRetainsFiniteBinary64AndExactIntegerWireSemantics()
    {
        var scope = Directory.CreateTempSubdirectory("gua-assertion-static-");
        try
        {
            var scenario = Json(await File.ReadAllTextAsync(Path.Combine(AppContext.BaseDirectory, "fixtures", "scenario.json")));
            scenario["goal"]!["success"] = Assertion("{\"type\":\"number\"}", "approximatelyEquals", Value("number", "1e308"), 1e308);
            var path = Path.Combine(scope.FullName, "scenario.json");
            await File.WriteAllTextAsync(path, scenario.ToJsonString());
            var result = await new StaticContractValidator([scope.FullName]).ValidateFileAsync(path);
            Assert.True(result.IsValid, result.Code);
            var success = Assert.IsType<ScenarioDocument>(result.Document).Goal.Success!;
            Assert.Equal("1e308", success["expected"]!["value"]!.ToJsonString());
            Assert.Equal(EvaluationResult.Known(true), PreparedAssertion.Create(success, Limits).EvaluateJson("{\"type\":\"number\",\"value\":1e308}"));
            scenario["goal"]!["success"] = Assertion("{\"type\":\"integer\"}", "equals", Value("integer", "1.00000000000000001"));
            await File.WriteAllTextAsync(path, scenario.ToJsonString());
            Assert.Equal("IntegerRange", (await new StaticContractValidator([scope.FullName]).ValidateFileAsync(path)).Code);
        }
        finally { scope.Delete(true); }
    }

    [Fact]
    public void RawJsonEntryPointsRejectDuplicatesAndReportSanitizedErrors()
    {
        var config = Assertion("{\"type\":\"integer\"}", "equals", Value("integer", "1")).ToJsonString();
        var prepared = PreparedAssertion.CreateJson(config, Limits);
        Assert.Equal(EvaluationResult.Known(true), prepared.EvaluateJson("{\"type\":\"integer\",\"value\":1e0}"));
        Assert.Equal(EvaluationError.ObservationContractViolation, prepared.EvaluateJson("{\"type\":\"integer\",\"value\":1,\"value\":2}").Error);
        var duplicate = config.Replace("\"value\":1", "\"value\":1,\"value\":2", StringComparison.Ordinal);
        Assert.Equal("DuplicateKey", Assert.Throws<AssertionConfigurationException>(() => PreparedAssertion.CreateJson(duplicate, Limits)).Code);
        var error = Assert.Throws<AssertionConfigurationException>(() => PreparedAssertion.CreateJson("{\"secret-token\":\"do-not-print\"}", Limits));
        Assert.DoesNotContain("do-not-print", error.Message); Assert.DoesNotContain("secret-token", error.Message);
    }
